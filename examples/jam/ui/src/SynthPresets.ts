import { DEFAULT_SYNTH } from './InstrumentPanel';
import type { SynthParams, SynthPreset } from './InstrumentPanel';

export interface FactoryPreset extends SynthPreset {
  category: string;
}

type Mx = Array<[src: 'cycenv' | 'env' | 'lfo' | 'velo' | 'key',
                dest: 'pitch' | 'wave' | 'timbre' | 'shape' | 'cutoff',
                amt: number]>;

const SRC = { cycenv: 0, env: 1, lfo: 2, velo: 3, key: 4 } as const;
const DST = { pitch: 0, wave: 1, timbre: 2, shape: 3, cutoff: 4 } as const;
const OSC = { analog: 0, supersaw: 1, wavetable: 2, fm: 3, harmonic: 4 } as const;
const FLT = { lp: 0, bp: 1, hp: 2 } as const;
const LFO = { sine: 0, tri: 1, saw: 2, sqr: 3, sh: 4 } as const;
const CYC = { env: 0, run: 1, loop: 2 } as const;
const ARP = { off: 0, up: 1, down: 2, ud: 3, rnd: 4, order: 5, ptn: 6 } as const;

function P(category: string, name: string, o: Partial<SynthParams>, mx: Mx = []): FactoryPreset {
  const matrix = Array(25).fill(0);
  for (const [s, d, a] of mx) matrix[SRC[s] * 5 + DST[d]] = a;
  return { name, category, params: { ...DEFAULT_SYNTH, ...o }, matrix };
}

